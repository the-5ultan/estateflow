CREATE TABLE users (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    google_id VARCHAR(255) NOT NULL,
    profile_image_url VARCHAR(2048),
    role VARCHAR(24) NOT NULL DEFAULT 'USER',
    account_status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_google UNIQUE (google_id),
    CONSTRAINT ck_user_role CHECK (role IN ('USER', 'AGENT', 'SUPER_ADMIN')),
    CONSTRAINT ck_account_status CHECK (account_status IN ('ACTIVE', 'SUSPENDED'))
) ENGINE=InnoDB;

CREATE TABLE agent_profiles (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    agency_name VARCHAR(160) NOT NULL,
    phone_number VARCHAR(16) NOT NULL,
    whatsapp_number VARCHAR(16),
    city VARCHAR(100) NOT NULL,
    office_address VARCHAR(500),
    bio VARCHAR(2000),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_agent_user UNIQUE (user_id),
    CONSTRAINT fk_agent_user FOREIGN KEY (user_id) REFERENCES users(id),
    INDEX idx_agent_city (city)
) ENGINE=InnoDB;

CREATE TABLE properties (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    agent_id BIGINT NOT NULL,
    title VARCHAR(180) NOT NULL,
    slug VARCHAR(220) NOT NULL,
    description TEXT NOT NULL,
    property_type VARCHAR(24) NOT NULL,
    listing_purpose VARCHAR(24) NOT NULL,
    price DECIMAL(15,2) NOT NULL,
    city VARCHAR(100) NOT NULL,
    area VARCHAR(160) NOT NULL,
    neighborhood VARCHAR(160),
    address VARCHAR(500) NOT NULL,
    bedrooms INT NOT NULL DEFAULT 0,
    bathrooms INT NOT NULL DEFAULT 0,
    kitchens INT NOT NULL DEFAULT 0,
    parking_spaces INT NOT NULL DEFAULT 0,
    property_size DECIMAL(12,2) NOT NULL,
    size_unit VARCHAR(24) NOT NULL,
    listing_status VARCHAR(24) NOT NULL DEFAULT 'AVAILABLE',
    payment_status VARCHAR(24) NOT NULL DEFAULT 'NOT_APPLICABLE',
    payment_option VARCHAR(24) NOT NULL DEFAULT 'FULL_PAYMENT',
    visibility VARCHAR(24) NOT NULL DEFAULT 'PRIVATE',
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    published_at TIMESTAMP(6),
    archived_at TIMESTAMP(6),
    CONSTRAINT uq_property_slug UNIQUE (slug),
    CONSTRAINT fk_property_agent FOREIGN KEY (agent_id) REFERENCES agent_profiles(id),
    CONSTRAINT ck_property_type CHECK (property_type IN ('HOUSE','APARTMENT','PLOT','COMMERCIAL')),
    CONSTRAINT ck_listing_purpose CHECK (listing_purpose IN ('SALE','RENT')),
    CONSTRAINT ck_listing_status CHECK (listing_status IN ('AVAILABLE','RESERVED','SOLD','RENTED')),
    CONSTRAINT ck_payment_status CHECK (payment_status IN ('NOT_APPLICABLE','PENDING','PARTIAL','PAID')),
    CONSTRAINT ck_payment_option CHECK (payment_option IN ('FULL_PAYMENT','INSTALLMENTS','BOTH')),
    CONSTRAINT ck_visibility CHECK (visibility IN ('PUBLIC','PRIVATE')),
    CONSTRAINT ck_size_unit CHECK (size_unit IN ('MARLA','KANAL','SQUARE_FEET','SQUARE_YARDS')),
    CONSTRAINT ck_property_price CHECK (price >= 0),
    CONSTRAINT ck_property_size CHECK (property_size > 0),
    CONSTRAINT ck_property_rooms CHECK (bedrooms >= 0 AND bathrooms >= 0 AND kitchens >= 0 AND parking_spaces >= 0),
    INDEX idx_public_search (visibility, archived_at, city, listing_purpose, property_type),
    INDEX idx_public_price (visibility, archived_at, price),
    INDEX idx_public_featured (visibility, archived_at, featured, published_at),
    INDEX idx_agent_properties (agent_id, archived_at, created_at),
    INDEX idx_property_area (city, area, neighborhood),
    INDEX idx_property_status (listing_status, payment_option),
    INDEX idx_property_size (size_unit, property_size),
    FULLTEXT INDEX idx_property_keywords (title, description)
) ENGINE=InnoDB;

CREATE TABLE property_images (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    property_id BIGINT NOT NULL,
    cloudinary_public_id VARCHAR(255) NOT NULL,
    image_url VARCHAR(2048) NOT NULL,
    alt_text VARCHAR(255) NOT NULL,
    display_order INT NOT NULL DEFAULT 0,
    cover_image BOOLEAN NOT NULL DEFAULT FALSE,
    -- MySQL allows multiple NULLs in a unique index: one cover per property.
    cover_property_id BIGINT GENERATED ALWAYS AS (CASE WHEN cover_image THEN property_id ELSE NULL END) STORED,
    CONSTRAINT uq_cloudinary_id UNIQUE (cloudinary_public_id),
    CONSTRAINT uq_property_cover UNIQUE (cover_property_id),
    CONSTRAINT uq_property_image_order UNIQUE (property_id, display_order),
    CONSTRAINT fk_image_property FOREIGN KEY (property_id) REFERENCES properties(id),
    CONSTRAINT ck_image_order CHECK (display_order >= 0)
) ENGINE=InnoDB;

CREATE TABLE installment_plans (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    property_id BIGINT NOT NULL,
    total_price DECIMAL(15,2) NOT NULL,
    down_payment DECIMAL(15,2) NOT NULL,
    installment_amount DECIMAL(15,2) NOT NULL,
    number_of_installments INT NOT NULL,
    payment_frequency VARCHAR(24) NOT NULL,
    description VARCHAR(2000),
    CONSTRAINT uq_installment_property UNIQUE (property_id),
    CONSTRAINT fk_installment_property FOREIGN KEY (property_id) REFERENCES properties(id),
    CONSTRAINT ck_installment_amounts CHECK (total_price > 0 AND down_payment >= 0 AND installment_amount > 0),
    CONSTRAINT ck_installment_count CHECK (number_of_installments BETWEEN 1 AND 1200),
    CONSTRAINT ck_installment_frequency CHECK (payment_frequency IN ('MONTHLY','QUARTERLY','YEARLY')),
    CONSTRAINT ck_installment_balance CHECK (down_payment + installment_amount * number_of_installments = total_price)
) ENGINE=InnoDB;
